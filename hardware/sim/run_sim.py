I_OPERATE = 3.75 / 70.0     # coil current at must-operate voltage
I_RELEASE = 0.5 / 70.0      # coil current at must-release voltage


def t1_measure(v, vsup):
    t = v["time"]
    vc, vp = v["c"], v["vp"]
    ic = v["v_ic#branch"]
    ib = v["v_ib#branch"]
    ig = v["v_ig#branch"]
    icoil = v["v_icoil#branch"]
    iled = v["v_iled#branch"]
    idf = v["v_id#branch"]
    pq = vc * ic + v["bq"] * ib
    on = 55e-3
    off = window(v, 60e-3, 120e-3)
    r = dict(
        ig_on=at(v, "v_ig#branch", on), ig_peak=float(np.max(np.abs(ig))),
        ib_on=at(v, "v_ib#branch", on), vce_on=at(v, "c", on),
        vcoil_on=at(v, "vp", on) - at(v, "c", on), icoil_on=at(v, "v_icoil#branch", on),
        iled_on=at(v, "v_iled#branch", on), pq_on=float(np.interp(on, t, pq)),
        pq_peak=float(np.max(pq)), vc_peak=float(np.max(vc[off])),
        id_peak=float(np.max(idf)), led_rev=float(np.max((vc - vp)[off])),
        t_pullin=None, t_release=None,
    )
    tp = first_cross(t, icoil, I_OPERATE, 10e-3, rising=True)
    r["t_pullin"] = None if tp is None else tp - 10e-3
    tr = first_cross(t, icoil, I_RELEASE, 60e-3, rising=False)
    r["t_release"] = None if tr is None else tr - 60e-3
    tr30 = first_cross(t, icoil, 0.3 * 0.0714, 60e-3, rising=False)
    r["t_30pct"] = None if tr30 is None else tr30 - 60e-3
    # avalanche energy into the transistor (Rav = 1 mohm sense when fitted)
    if "nav" in v:
        iav = v["nav"] / 1e-3
        pav = np.clip(iav, 0, None) * vc
        r["e_aval"] = float(np.trapezoid(pav, t)) if hasattr(np, "trapezoid") else float(np.trapz(pav, t))
        r["iav_peak"] = float(np.max(iav))
    return r


