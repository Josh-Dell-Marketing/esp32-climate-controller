def check(test, name, value, limit, status):
    CHECKS.append((test, name, value, limit, status))
    print(f"[{status:8s}] {test} | {name}: {value}  (limit {limit})")


def pf(ok, marginal=False):
    if ok and marginal:
        return "MARGINAL"
    return "PASS" if ok else "FAIL"


def variant(src, name, params=None, subs=None):
    """Write build/<name>.cir = src with .param values / text substitutions applied."""
    with open(os.path.join(HERE, src), encoding="utf-8") as f:
        text = f.read()
    for k, v in (params or {}).items():
        text, n = re.subn(rf"^\.param\s+{k}=.*$", f".param {k}={v}", text, flags=re.M)
        if n != 1:
            raise KeyError(f"{src}: .param {k} not found")
    for old, new in (subs or []):
        if old not in text:
            raise KeyError(f"{src}: text {old!r} not found")
        text = text.replace(old, new)
    text = text.replace(".include models/", ".include ../models/")
    text = f"* GENERATED by run_sim.py from {src} - case {name}\n" + text
    path = os.path.join(BUILD, name + ".cir")
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    return ng.run_file(path)


def at(v, key, t):
    return float(np.interp(t, v["time"], v[key]))


def window(v, t0, t1):
    t = v["time"]
    return (t >= t0) & (t <= t1)


def first_cross(t, y, level, t_start, rising=True):
    m = t >= t_start
    tt, yy = t[m], y[m]
    idx = np.nonzero(yy >= level)[0] if rising else np.nonzero(yy <= level)[0]
    if len(idx) == 0:
        return None
    i = idx[0]
    if i == 0:
        return tt[0]
    # linear interpolation between samples
    return float(np.interp(level, [yy[i - 1], yy[i]], [tt[i - 1], tt[i]])) if yy[i] != yy[i - 1] else tt[i]


def ma(x):
    return f"{x * 1e3:.2f} mA"


