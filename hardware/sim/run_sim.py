AMS_DROPOUT = 1.1
AMS_MIN_IN = 3.3 + AMS_DROPOUT


def t3_measure(v):
    t = v["time"]
    vp = v["vp"]
    after = window(v, 10e-3, 60e-3)
    last = window(v, 40e-3, 60e-3)
    iin = v["v_iin#branch"]
    vf = v["dan"] - vp
    r = dict(
        v_pre=at(v, "vp", 9.5e-3), v_min=float(np.min(vp[after])),
        v_on_quiet=at(v, "vp", 58e-3), v_burst_min=float(np.min(vp[window(v, 50e-3, 52.5e-3)])),
        i_avg=float(np.mean(iin[last])), i_quiet=at(v, "v_iin#branch", 58e-3), i_peak=float(np.max(iin)),
        vf_peak=float(np.max(vf[after])), vf_quiet=float(np.interp(58e-3, t, vf)),
        pd=float(np.mean((vf * iin)[last])),
        i_usb_avg=float(np.mean(v["v_iusb#branch"][last])), i_usb_peak=float(np.max(v["v_iusb#branch"])),
        i_back=float(np.min(iin)),
        i_relays=at(v, "v_ir#branch", 58e-3),
    )
    return r


