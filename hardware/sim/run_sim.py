# TEST 5 - relay contact trace temperature rise (hand calculation)
# ---------------------------------------------------------------------------
def run_test5():
    """IPC-2221 external-layer formula: I = k * dT^0.44 * A^0.725, k = 0.048, A in mil^2."""
    T = "5 Traces"
    k = 0.048
    w_mil = 2.0 / 0.0254
    t_mil = 35e-3 / 0.0254
    a1 = w_mil * t_mil
    rho = 1.72e-8 * (1 + 0.00393 * 20)       # copper at ~40 C
    r1 = rho * 25e-3 / (2.0e-3 * 35e-6)       # one 25 mm trace
    rpar = r1 / 2

    def dT(i, a):
        return (i / (k * a ** 0.725)) ** (1 / 0.44)

    def imax(dt, a):
        return k * dt ** 0.44 * a ** 0.725

    rows = []
    for i in (3, 5, 8, 10):
        cons = dT(i, 2 * a1)            # top+bottom treated as ONE conductor of 2x area (conservative)
        split = dT(i / 2, a1)           # each layer carries I/2 and cools on its own (optimistic)
        rows.append((i, cons, split, i * i * rpar, i * rpar))
        check(T, f"{i} A: temperature rise (conservative / optimistic)",
              f"{cons:.1f} / {split:.1f} C   (drop {i * rpar * 1e3:.0f} mV, {i * i * rpar * 1e3:.0f} mW)",
              "<= 20 C", pf(cons <= 20))
    i20c, i20s = imax(20, 2 * a1), 2 * imax(20, a1)
    check(T, "Max current for 20 C rise (conservative / optimistic)", f"{i20c:.1f} A / {i20s:.1f} A",
          "document per-channel limit", "INFO")
    NOTES["t5"] = dict(rows=rows, a1=a1, i20c=i20c, i20s=i20s, r1=r1, rpar=rpar, w_mil=w_mil, t_mil=t_mil)


