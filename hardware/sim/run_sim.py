def run_test2():
    T = "2 Boot"
    cases = [
        ("open (hi-Z)", {"RSRC": "1T"}),
        ("30 uA leakage", {"RSRC": "1T", "ILEAK": "30u"}),
        ("pull-up 30k to 3.3 V", {"VG0": 3.3, "VG1": 3.3, "RSRC": "30k"}),
        ("pull-up 50k to 3.3 V", {"VG0": 3.3, "VG1": 3.3, "RSRC": "50k"}),
    ]
    out = {}
    for rpd in ("10k", "4.7k"):
        for lab, p in cases:
            name = "t2_" + re.sub(r"[^A-Za-z0-9]+", "_", lab) + f"_rpd{rpd}"
            v = variant("test2_boot.cir", name, dict(p, RPD=rpd))
            mk = window(v, 20e-3, 100e-3)
            vcoil = float(np.max((v["vp"] - v["c"])[mk]))
            icq = float(np.max(v["v_ic#branch"][mk]))
            vb = float(np.max(v["b"][mk]))
            out[(lab, rpd)] = (vcoil, icq, vb)
            ok = vcoil < 0.5
            fully_off = icq < 100e-6
            if rpd == "10k" or not ok or "pull-up" in lab:
                check(T, f"{lab}, Rpd={rpd}: coil V / Ic / Vbe",
                      f"{vcoil * 1e3:.0f} mV / {icq * 1e6:.0f} uA / {vb:.2f} V",
                      "coil < 0.5 V (ideally Ic < 0.1 mA)",
                      "PASS" if (ok and fully_off) else ("MARGINAL" if ok else "FAIL"))
    NOTES["t2"] = out
    # GPIO16 50 ms high at boot
    v = variant("test2_boot.cir", "t2_gpio16_50ms_pulse",
                {"VG0": 0, "VG1": 3.3, "TD": "10m", "TPW": "50m", "RSRC": 30})
    t, ic = v["time"], v["v_icoil#branch"]
    tp = first_cross(t, ic, I_OPERATE, 10e-3)
    tr = first_cross(t, ic, I_RELEASE, 60e-3, rising=False)
    NOTES["t2_gpio16"] = (tp - 10e-3, tr - 60e-3)
    check(T, "GPIO16 high 50 ms at boot (fan channel)",
          f"coil reaches must-operate after {(tp - 10e-3) * 1e3:.1f} ms -> relay CLICKS ON for ~50 ms",
          "accepted for the fan (document it)", "INFO")
    fig, ax = plt.subplots(figsize=(9, 4))
    ax.plot(t * 1e3, ic * 1e3, label="coil current, GPIO16 50 ms boot pulse")
    ax.axhline(I_OPERATE * 1e3, color="g", lw=0.8, ls=":", label="must-operate")
    ax.set_xlabel("time (ms)"); ax.set_ylabel("mA"); ax.grid(alpha=.3); ax.legend(fontsize=8)
    ax.set_title("Test 2: GPIO16 boot glitch (fan relay)")
    fig.tight_layout(); fig.savefig(os.path.join(PLOTS, "test2_gpio16_boot_pulse.png"), dpi=110); plt.close(fig)


