"""Writes SIM_REPORT.md from the checks and numbers collected by run_sim.py."""
from datetime import date


def _status(s):
    if " / " in s:  # I2C: "100 kHz / 400 kHz"
        a, b = s.split(" / ")
        return f"100k {_status(a)}, 400k {_status(b)}"
    return {"FAIL": "**FAIL**", "MARGINAL": "**MARGINAL**"}.get(s, s)


def _esc(x):
    return str(x).replace("|", "\\|")


def write(checks, notes, path):
    t1 = notes["t1"]
    t3 = notes["t3"]
    t5 = notes["t5"]
    g16 = notes["t2_gpio16"]
    pu30 = notes["t2"][("pull-up 30k to 3.3 V", "10k")]
    pu50 = notes["t2"][("pull-up 50k to 3.3 V", "10k")]
    n5 = t1[(5.0, "150m", "diode")]
    wc = t1[(4.5, "150m", "lowgain")]
    wc47 = t1[(4.5, "150m", "lowgain_rpd4k7")]
    p50, p475, p50m, p475m = t3[(5.0, "typ")], t3[(4.75, "typ")], t3[(5.0, "max")], t3[(4.75, "max")]
    usb = t3[("usb5.0", "open")]
    usb475 = t3[("usb4.75", "open")]

    lines = []
    w = lines.append
    w("# Relay carrier PCB: circuit simulation report")
    w("")
    w(f"Generated by `run_sim.py` on {date.today().isoformat()} with ngspice (KiCad 10.0.8 `ngspice.dll`). "
      "Re-run with `.venv\\Scripts\\python.exe run_sim.py` from this folder. Every number below comes from that run, "
      "except test 5, which is a hand calculation in the same script.")
    w("")
    w("## Verdict")
    w("")
    w("The relay driver design is sound. Base drive, saturation, coil voltage at 4.5 V, the flyback clamp, the LED and "
      "transistor dissipation all pass with large margin. Nothing in the driver depends on the unknown coil inductance; "
      "the inductance changes only the timing.")
    w("")
    w("Three things need a decision before ordering, and one needs documenting:")
    w("")
    w(f"1. **Power path headroom for the NodeMCU's AMS1117 (FAIL at the edges).** The 1N5819 plus polyfuse drop leaves "
      f"the +5V rail at {p50['v_min']:.2f} V minimum with a 5.00 V supply and a typical diode (only "
      f"{(p50['v_min'] - 4.4) * 1e3:.0f} mV above the 4.4 V the AMS1117 needs). It falls to {p50m['v_min']:.2f} V with a "
      f"diode at its datasheet-max Vf, and to {p475['v_min']:.2f}-{p475m['v_min']:.2f} V with a 4.75 V supply. The relays "
      "are not affected; they only need 3.75 V. In dropout the AMS1117 output sags to about rail - 1.1 V "
      f"(down to ~{p475m['v_min'] - 1.1:.2f} V). The ESP8266 is specified down to 2.5 V, so it will probably keep running, "
      "but there is no margin. **Fix, choose one:**")
    w("   - **A (recommended):** replace D_REV with an ideal-diode IC that blocks reverse current, e.g. TI **LM66100** "
      "(SC-70-6, 1.5-5.5 V, 1.5 A, 79 mohm typ, reverse-current blocking, reverse-polarity standoff to -6 V). Simulated as an 80 mohm path: rail minimum "
      f"{t3[(4.75, 'ideal')]['v_min']:.2f} V even at a 4.75 V input. Do **not** use a plain P-MOSFET with its gate tied "
      "to GND: it conducts both ways, so with the NodeMCU on USB it would back-feed the input terminal. The 1N5819 "
      "and LM66100 do not.")
    w(f"   - **B:** keep the 1N5819 and specify the supply as 5.1-5.25 V (most DIN-rail and open-frame 5 V supplies "
      f"have a trim pot). At 5.25 V with a datasheet-max diode the rail minimum is {t3[(5.25, 'max')]['v_min']:.2f} V.")
    w("   - C: a lower-Vf Schottky (3-5 A part, e.g. 1N5822 / SS54 / a Nexperia PMEG low-VF part) gains roughly "
      "0.05-0.15 V at 0.4 A. That helps but does not fix the 4.75 V case on its own.")
    w(f"2. **Boot with an internal pull-up enabled (FAIL with Rpd = 10 k).** If GPIO12/13/14 come up with the internal "
      f"~30 k pull-up enabled, the 30 k / (1 k + 10 k) divider puts {pu30[2]:.2f} V on the base. Q1 then conducts "
      f"{pu30[1] * 1e3:.1f} mA and the coil sees {pu30[0] * 1e3:.0f} mV, above the 0.5 V must-release level. The relay "
      f"will not click (it needs 3.75 V), but it is not \"fully off\". A 50 k pull-up gives {pu50[1] * 1e6:.0f} uA (marginal). "
      "The ESP8266 does not normally enable these pull-ups unless firmware sets INPUT_PULLUP, so in practice this is a "
      "robustness margin. **Fix: change Rpd from 10 k to 4.7 k.** Q1 then stays fully off (Vbe <= 0.43 V, Ic ~2 uA) with "
      f"a 30 k pull-up. Drive stays fine at the worst case (4.5 V, hFE ~250 model, 40 ohm GPIO): coil {wc47['vcoil_on']:.2f} V, "
      f"Vce(sat) {wc47['vce_on'] * 1e3:.0f} mV, GPIO current ~{(wc47['ig_on']) * 1e3:.1f} mA.")
    w("3. **I2C at 400 pF fails at 100 kHz; 400 kHz only works for very short cables.** A 0.5-1 m cable plus the SHT31 "
      "and the ESP8266 pins is typically 80-150 pF. That passes at 100 kHz with 4.7 k alone (< ~250 pF) or 4.7 k || 10 k "
      "(< ~370 pF). **Run the bus at 100 kHz.** If the cable is long or shielded (higher pF), fit **2.2 k** pull-ups on the "
      "carrier: 611 ns at 400 pF, with sink current 1.6 mA, still inside 3 mA.")
    w(f"4. **Contact traces: document {int(t5['i20c'])} A per channel** (conservative IPC-2221 limit for a 20 C rise is "
      f"{t5['i20c']:.1f} A). 10 A gives about 26 C rise on the conservative method. See test 5.")
    w("")
    w("Also worth knowing:")
    w("")
    w(f"- USB-only power works: relays pull in (rail >= {usb475['v_min']:.2f} V at a 4.75 V USB port) and the 1N5819 "
      f"blocks back-feed into the input terminal (~55 uA model leakage, even into a 1 ohm dead supply). The AMS1117 "
      "headroom is marginal on a 4.75 V port, as in point 1. Four relays plus the NodeMCU draw "
      f"{usb['i_usb_avg'] * 1e3:.0f} mA average and {usb['i_usb_peak'] * 1e3:.0f} mA peak through the USB port and the NodeMCU's "
      "onboard USB diode. That is over a USB 2.0 port's 500 mA during WiFi bursts. Check the diode fitted on your "
      "NodeMCU (clones vary) and avoid running all four relays from a laptop USB port for long.")
    w(f"- GPIO16 boot glitch (fan channel): a 50 ms high at boot pulls the relay in after {g16[0] * 1e3:.1f} ms; it releases "
      f"{g16[1] * 1e3:.1f} ms after the pin goes low (L = 150 mH). The fan relay will click on briefly at every boot. "
      "That is accepted; document it.")
    w("")
    w("## Results table")
    w("")
    w("| Test | Check | Value | Limit | Result |")
    w("|---|---|---|---|---|")
    for test, name, value, limit, status in checks:
        w(f"| {_esc(test)} | {_esc(name)} | {_esc(value)} | {_esc(limit)} | {_status(status)} |")
    w("")
    w("FAIL rows under \"WITHOUT flyback diode\" are expected: they show why the 1N4148 is needed. FIX rows test the proposed changes.")
    w("")
    w("## Notes per test")
    w("")
    w("### 1. Relay driver (`test1_relay_driver.cir`, plots `test1_*.png`)")
    w("")
    w(f"- The base gets {n5['ib_on'] * 1e3:.2f} mA ((3.3 - 0.75) / 1 k, minus 75 uA into Rpd). With ~71 mA collector current "
      f"that is a forced beta of ~{n5['icoil_on'] / n5['ib_on']:.0f}, far below the BC337-40's minimum hFE of 250, so Q1 is "
      f"hard in saturation: Vce(sat) {n5['vce_on'] * 1e3:.0f} mV. Even the low-gain model at 4.5 V gives forced beta "
      f"{wc['icoil_on'] / wc['ib_on']:.0f}. 1 k is a good value; no change needed.")
    w(f"- Coil voltage when on is supply minus ~55 mV: {n5['vcoil_on']:.2f} V at 5.0 V and "
      f"{t1[(4.5, '150m', 'diode')]['vcoil_on']:.2f} V at 4.5 V (must-operate 3.75 V). The relays will still pull in "
      f"down to a rail of about 3.8 V.")
    w(f"- Turn-off with the 1N4148: the collector clamps at {n5['vc_peak']:.2f} V (supply + ~0.8 V). The diode carries the "
      f"coil current ({n5['id_peak'] * 1e3:.0f} mA peak, decaying over a few ms), well within the 1N4148's 200 mA average "
      "rating and 1 A / 1 ms surge rating.")
    w("- Turn-off without the diode: nothing limits the collector except Q1's own breakdown. In the model with no "
      f"breakdown it rings up to {t1[(5.0, '150m', 'nodiode_noaval')]['vc_peak'] / 1000:.1f} kV. With the BC337's "
      f"V(BR)CES = 50 V modelled, Q1 avalanches at ~50 V (above Vceo 45 V) and absorbs the coil energy "
      f"(up to {max(t1[(5.0, L, 'nodiode')]['e_aval'] for L in ('50m', '150m', '500m')) * 1e3:.2f} mJ per switch-off at "
      f"500 mH). The BC337 has no avalanche energy rating. The LED also sees "
      f"{t1[(5.0, '150m', 'nodiode')]['led_rev']:.0f} V reverse (rated 5 V). The 1N4148 is required.")
    w("- Coil inductance sweep (50 / 150 / 500 mH): all steady-state values (base current, Vce(sat), coil voltage, LED "
      "current, clamp voltage, diode peak current) are identical across the sweep. Only the timing scales with L/R:")
    for L in ("50m", "150m", "500m"):
        r = t1[(5.0, L, "diode")]
        w(f"  - L = {L}H: coil current reaches the must-operate level {r['t_pullin'] * 1e3:.1f} ms after the GPIO goes "
          f"high; after the GPIO goes low it falls below 30 % in {r['t_30pct'] * 1e3:.1f} ms and below the 10 % must-release "
          f"level in {r['t_release'] * 1e3:.1f} ms.")
    w("  The real release delay is the decay time plus the armature's mechanical release (datasheet: release <= 5 ms). "
      "A diode-only clamp makes the release slower than a zener clamp would, which is normal and harmless here. "
      "Only consider a zener + diode clamp if fast release ever matters.")
    w(f"- LED current {n5['iled_on'] * 1e3:.1f} mA at 5.0 V ({t1[(4.5, '150m', 'diode')]['iled_on'] * 1e3:.1f} mA at 4.5 V), "
      f"as expected. It is carried by Q1 in addition to the coil.")
    w(f"- Q1 dissipation is {n5['pq_on'] * 1e3:.1f} mW when on, against 625 mW for the TO-92. The {max(r['pq_peak'] for k, r in t1.items() if k[2] == 'diode') * 1e3:.0f} mW "
      "peak lasts well under a microsecond, during the switching edge.")
    w("")
    w("### 2. Boot (`test2_boot.cir`, plot `test2_gpio16_boot_pulse.png`)")
    w("")
    w("- Open (hi-Z) pin: Rpd holds the base at 0 V. Relay off, Ic = 0. PASS.")
    w("- 30 uA leakage into the pin: 30 uA x 10 k = 0.3 V on the base. Q1 off. PASS.")
    w("- Internal pull-up 30-50 k: see the Verdict, point 2. Change Rpd to 4.7 k.")
    w("- GPIO16 50 ms high at boot: the relay pulls in. Accepted for the fan; document it.")
    w("")
    w("### 3. Power path (`test3_power_path.cir`, plot `test3_rail_droop.png`)")
    w("")
    w("- Stimulus: all four relays switch on together at 10 ms. The NodeMCU draws 80 mA with 300 mA WiFi bursts "
      "(2 ms every 10 ms), the first one exactly at the relay switch-on. This is harsher than real WiFi traffic.")
    w(f"- Voltage budget at a 5.00 V input, all relays on, between bursts (~{p50['i_quiet'] * 1e3:.0f} mA): lead ~"
      f"{p50['i_quiet'] * 0.02 * 1e3:.0f} mV, polyfuse ~{p50['i_quiet'] * 0.25 * 1e3:.0f} mV (0.25 ohm), 1N5819 "
      f"{p50['vf_quiet'] * 1e3:.0f} mV typical / {p50m['vf_quiet'] * 1e3:.0f} mV datasheet-max. Rail "
      f"{p50['v_on_quiet']:.2f} V / {p50m['v_on_quiet']:.2f} V. A 300 mA burst takes a further ~0.1 V. The 470 uF capacitor "
      "smooths the 10 us edges, but a 2 ms burst is too long for it to carry.")
    w("- The polyfuse resistance is the brief's 0.25 ohm. Check the MF-R110's R1max (resistance after it has tripped once). "
      "Each extra 0.1 ohm costs about 40 mV at 0.4 A.")
    w(f"- Total current: {p50['i_quiet'] * 1e3:.0f} mA with all relays on and the NodeMCU at 80 mA; "
      f"{p50['i_avg'] * 1e3:.0f} mA average including bursts; {p50['i_peak'] * 1e3:.0f} mA peak. That is well inside F1's "
      "1.1 A hold current, which derates to roughly 0.9 A at 50 C ambient. F1 will not nuisance-trip.")
    w(f"- 1N5819 dissipation {p50['pd'] * 1e3:.0f}-{p50m['pd'] * 1e3:.0f} mW. Fine for a DO-41 part.")
    w("- The Diodes Inc DI_1N5819 model is shown for reference only. It gives ~0.76 V at 1 A, which is beyond the "
      "0.60 V datasheet maximum, so it overstates the drop.")
    w("- USB-only mode: modelled as the USB port -> 0.25 ohm cable -> the NodeMCU's series Schottky (~0.35 V at 0.4 A) -> "
      "+5V. The input terminal is either open or loaded by 1 ohm (a dead supply). The 1N5819's reverse leakage is the only "
      "back-feed path.")
    w("- Fix A (LM66100-class ideal diode) is modelled only as its forward on-resistance. Its reverse-current blocking (internal "
      "comparator) and -6 V reverse-polarity standoff are from the TI datasheet and are not simulated. Check its 5.5 V "
      "maximum input against your supply's worst-case overshoot; a reversed 5 V supply (-5 V) is inside its -6 V rating with little margin.")
    w("")
    w("### 4. I2C (`test4_i2c_rise.cir`, plot `test4_i2c_rise.png`)")
    w("")
    w("- The rise time follows 0.847 x R x C, as the simulation confirms. Limits: 1000 ns for 100 kHz, 300 ns for 400 kHz "
      "(I2C spec, 30-70 %).")
    w("- Sink current at VOL = 0.4 V: 0.62 mA (4.7 k) and 0.91 mA (4.7 k || 10 k), far below the 3 mA limit. You could "
      "go as low as ~1 k total pull-up before reaching 3 mA.")
    w("- Recommendation: 100 kHz in firmware. Keep 4.7 k on the carrier, and leave the footprint so 2.2 k can be fitted "
      "for a long or shielded cable.")
    w("")
    w("### 5. Relay contact traces (hand calculation, IPC-2221)")
    w("")
    w(f"- Method: the IPC-2221 external-layer formula I = 0.048 x dT^0.44 x A^0.725 (A in mil^2). One trace, 2.0 mm x "
      f"35 um = {t5['w_mil']:.1f} mil x {t5['t_mil']:.2f} mil = {t5['a1']:.0f} mil^2. IPC-2152 was not used: it is chart-based "
      "and needs board-thickness and plane modifiers we do not have yet. For a single external trace on 1.6 mm FR4 "
      "with no planes it gives results of the same order.")
    w("- Top and bottom copies run directly over each other on a 1.6 mm board, so they heat each other. Two bounds are "
      "given. **Conservative:** one conductor of twice the area (2 x 108.5 mil^2). **Optimistic:** each layer carries "
      "half the current and cools on its own. Use the conservative figure.")
    w("")
    w("| Current | dT conservative | dT optimistic | Drop (25 mm, both layers) | Power in trace |")
    w("|---|---|---|---|---|")
    for i, c, s, p, dv in t5["rows"]:
        w(f"| {i} A | {c:.1f} C | {s:.1f} C | {dv * 1e3:.0f} mV | {p * 1e3:.0f} mW |")
    w("")
    w(f"- Max current for a 20 C rise: **{t5['i20c']:.1f} A conservative**, {t5['i20s']:.1f} A optimistic. "
      f"Trace resistance is {t5['r1'] * 1e3:.1f} mohm per layer ({t5['rpar'] * 1e3:.1f} mohm both layers, copper at 40 C).")
    w(f"- **Document a per-channel limit of {int(t5['i20c'])} A continuous (resistive).** Other parts of the path may "
      "set a lower limit. The SRD-05VDC-SL-C is rated 10 A at 250 VAC / 30 VDC resistive, and much less for motor or "
      "inductive loads; check its datasheet derating. The screw terminal block's rating and the relay pins themselves "
      "may also be lower. Both trace ends land on through-hole pads, which already join the top and bottom copper; "
      "a few stitching vias along the 25 mm run do no harm.")
    w("")
    w("## Assumptions")
    w("")
    w("- **Coil inductance:** not in the Songle datasheet. 150 mH is the nominal value. Bench measurements of this relay "
      "family are roughly 0.1-0.2 H, and L/R ~2 ms fits the 10 ms operate / 5 ms release spec. Results are reported "
      "for 50, 150 and 500 mH; only the timing changes. Coil inter-winding capacitance is assumed at 20 pF (it matters "
      "only without the diode). The coil is 70 ohm.")
    w("- **ESP8266 GPIO:** 3.3 V push-pull with 30 ohm output resistance (40 ohm in the worst-case run). Internal pull-up "
      "30-50 k. Leakage 30 uA.")
    w("- **NodeMCU load:** an ideal current sink, 80 mA plus 300 mA / 2 ms bursts every 10 ms. No input capacitance "
      "on the NodeMCU board was assumed (conservative). AMS1117 minimum input = 3.3 V + 1.1 V dropout = 4.4 V.")
    w("- **Supply lead:** 20 mohm, 0.5 uH. Polyfuse: 0.25 ohm. C1 ESR 0.1 ohm. USB cable: 0.25 ohm. NodeMCU USB diode: "
      "modelled with the typical 1N5819 card (~0.35 V at 0.4 A).")
    w("- **Transistor model:** Philips/NXP BC337-40 Gummel-Poon card, as distributed in the LTspice libraries and in "
      "KiCad-Spice-Library BJT.lib (BF = 436.8). A copy with BF = 250 covers the hFE minimum. The model has no "
      "breakdown, so the BC337's V(BR)CES = 50 V is added as a separate breakdown diode (D_BVCES).")
    w("- **Diode models:** 1N4148 and 1N5819: the onsemi cards from the LTspice library (also in KiCad-Spice-Library "
      "DIODE2.lib). 1N5819_MAX: fitted here to the datasheet maximum, 0.60 V at 1 A. DI_1N5819: the Diodes Inc published "
      "model. Red LED: fitted to Vf ~1.95 V at 3 mA. All are in `models/`.")
    w("- **I2C:** the open-drain driver is a 60 ohm switch. Bus capacitance is a parameter; the real cable is not modelled.")
    w("- Simulations run at 27 C. Integration method: gear. Trapezoidal integration left an artificial, undamped "
      "L-C ring in the coil after release.")
    w("")
    w("## Files")
    w("")
    w("- `test1_relay_driver.cir`, `test2_boot.cir`, `test3_power_path.cir`, `test4_i2c_rise.cir`: the test netlists, "
      "with default parameters.")
    w("- `models/BC337-40.lib`, `models/diodes.lib`, `models/relay_channel.lib`: the device models, the relay coil and "
      "one full driver channel (used by test 3).")
    w("- `run_sim.py`: runs every case and writes this report. `ngspice_shared.py`: a ctypes driver for KiCad's "
      "`ngspice.dll`. `report.py`: the report writer.")
    w("- `build/*.cir`: the exact netlist of every case that ran (regenerated on each run).")
    w("- `plots/*.png`: the key waveforms.")
    w("")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
